"""Read-only regression checks for direct-booking trust, terms and UX."""
import re
import unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
H=(ROOT/'templates/index.html').read_text(encoding='utf-8')
JS=(ROOT/'static/js/app.js').read_text(encoding='utf-8')
S=(ROOT/'stability.py').read_text(encoding='utf-8')
STYLE=(ROOT/'static/css/homepage-slim.css').read_text(encoding='utf-8')
BANK=(ROOT/'bank_booking.py').read_text(encoding='utf-8')

class CheckoutTrustTests(unittest.TestCase):
    def test_core_checkout_still_present(self):
        for marker in ('id="bookingForm"','id="checkAvailability"','id="bookingSubmit"',
                       'id="guestArea"','id="liveCalendar"','id="continueBooking"',
                       'id="arrival"','id="departure"','id="priceBreakdown"',
                       'id="stripePaymentOption"','id="openGallery"','id="jause"'):
            # jause is generated by Jinja variable; check its source instead
            if marker == 'id="jause"':
                self.assertIn("['jause', 'luggage']", H)
            else:
                self.assertIn(marker, H)
    def test_no_unverified_availability_checkout(self):
        self.assertNotIn('status === "free" || status === "unknown"', JS)
        self.assertIn('status === "free" && Number.isFinite(Number(data.total))', JS)
        self.assertIn('if (!Number.isFinite(lastQuotedTotal) || lastQuotedTotal <= 0)', JS)
    def test_bank_payment_truth(self):
        self.assertIn("status='confirmed'", BANK)
        self.assertIn('PAYMENT_HOURS = 48', BANK)
        self.assertIn("48 Stunden", S)
        self.assertIn('zahlungspflichtig', JS.lower())
        self.assertNotIn('Der Termin wird erst nach persönlicher Bestätigung', JS)
        self.assertNotIn('Diese Anfrage blockiert den Zeitraum noch nicht', S)
    def test_checkout_terms_and_taxes_are_visible(self):
        self.assertIn('id="termsAccepted"', H)
        self.assertRegex(H,r'id="termsAccepted"[^>]*required')
        self.assertIn('href="/legal/agb"', H)
        self.assertIn('href="/legal/storno"', H)
        self.assertIn('href="/legal/datenschutz"', H)
        self.assertIn('id="taxDisclosure"', H)
        self.assertIn('2,60 €', H)
        self.assertIn('2,70 €', H)
        self.assertIn('2,70 €', S)
        self.assertIn('Zahlungsdienstleister Stripe', S)
        self.assertIn('§ 18 Abs. 1 Z 10 FAGG', S)
    def test_public_trust_copy(self):
        self.assertNotIn('8,8/10 Booking', H)
        self.assertNotIn('4,9 Google · 9', H)
        self.assertIn('exklusivem Bad direkt gegenüber', H)
        self.assertNotIn('>Verwaltung</a>', H)
        self.assertIn('Privatzimmer Wachau', H)
    def test_date_first_and_disclosed_extras(self):
        self.assertLess(H.index('class="booking-grid"'),H.index('class="zab-extras-details"'))
        self.assertIn('class="zab-extras-details"',H)
        self.assertIn('zab-terms-ack',STYLE)
    def test_anchor_targets_no_duplicates(self):
        ids=re.findall(r'id="([^"]+)"',H)
        # Jinja-generated field IDs are dynamic and intentionally excluded
        self.assertEqual(len(ids),len(set(ids)))
        for anchor in re.findall(r'href="#([^"]+)"',H):
            self.assertIn(anchor,ids)
if __name__=='__main__':unittest.main()
